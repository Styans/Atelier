export type MessageKey = keyof typeof ru;

export function t(key: MessageKey, values?: Record<string, string | number>): string {
  let text: string = ru[key];
  for (const [name, value] of Object.entries(values ?? {})) {
    text = text.replace(`{${name}}`, String(value));
  }
  return text;
}

/** A label that may be missing from the dictionary (metric names come from validators). */
export function tOr(key: string, fallback: string): string {
  return key in ru ? ru[key as MessageKey] : fallback;
}

/** "3 модели": the count with a word whose forms are stored as "one|few|many". */
export function plural(count: number, key: MessageKey): string {
  const [one, few, many] = ru[key].split("|");
  const n = Math.abs(count) % 100;
  const last = n % 10;
  const form = n >= 11 && n <= 14 ? many : last === 1 ? one : last >= 2 && last <= 4 ? few : many;
  return `${count} ${form ?? one}`;
}
